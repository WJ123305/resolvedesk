CREATE TABLE tenants (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL
);
CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL REFERENCES tenants(id),
 email VARCHAR(200) NOT NULL UNIQUE,
 name VARCHAR(100) NOT NULL,
 password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','AGENT','CUSTOMER')),
 UNIQUE (tenant_id, id)
);
CREATE TABLE tickets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL REFERENCES tenants(id),
 title VARCHAR(200) NOT NULL,
 description TEXT NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('OPEN','IN_PROGRESS','WAITING','RESOLVED','CLOSED')),
 priority VARCHAR(20) NOT NULL CHECK (priority IN ('LOW','MEDIUM','HIGH','URGENT')),
 created_by BIGINT NOT NULL,
 assignee_id BIGINT,
 version INTEGER NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE (tenant_id, id),
 FOREIGN KEY (tenant_id, created_by) REFERENCES app_users(tenant_id,id),
 FOREIGN KEY (tenant_id, assignee_id) REFERENCES app_users(tenant_id,id)
);
CREATE INDEX idx_ticket_tenant_updated ON tickets(tenant_id,updated_at DESC,id DESC);
CREATE INDEX idx_ticket_tenant_status ON tickets(tenant_id,status);
CREATE TABLE ticket_comments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL,
 ticket_id BIGINT NOT NULL,
 author_id BIGINT NOT NULL,
 body TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (tenant_id,ticket_id) REFERENCES tickets(tenant_id,id),
 FOREIGN KEY (tenant_id,author_id) REFERENCES app_users(tenant_id,id)
);
CREATE TABLE ticket_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL,
 ticket_id BIGINT NOT NULL,
 actor_id BIGINT NOT NULL,
 action VARCHAR(50) NOT NULL,
 detail VARCHAR(500) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (tenant_id,ticket_id) REFERENCES tickets(tenant_id,id),
 FOREIGN KEY (tenant_id,actor_id) REFERENCES app_users(tenant_id,id)
);
CREATE TABLE articles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL REFERENCES tenants(id),
 title VARCHAR(200) NOT NULL,
 body TEXT NOT NULL,
 published BOOLEAN NOT NULL DEFAULT FALSE,
 version INTEGER NOT NULL DEFAULT 0,
 author_id BIGINT NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (tenant_id,author_id) REFERENCES app_users(tenant_id,id)
);
